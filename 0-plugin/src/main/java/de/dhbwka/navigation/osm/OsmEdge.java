package de.dhbwka.navigation.osm;

import de.dhbwka.navigation.GeoEdge;
import de.dhbwka.navigation.GeoNode;


public class OsmEdge<NodeType extends GeoNode> implements GeoEdge<NodeType> {

    private final NodeType origin;
    private final NodeType destination;

    private final boolean directed;

    private final StreetType type;

    private final double width;

    public OsmEdge(NodeType origin, NodeType destination, boolean directed, StreetType type, double width) {
        this.origin = origin;
        this.destination = destination;
        this.directed = directed;
        this.type = type;
        this.width = width;
    }

    private static final boolean DIRECTED_DEFAULT = true;
    private static final StreetType TYPE_DEFAULT = StreetType.STREET;

    public OsmEdge(NodeType origin, NodeType destination, boolean directed, double width) {
        this(origin, destination, directed, TYPE_DEFAULT, width);
    }

    public OsmEdge(NodeType origin, NodeType destination, StreetType type, double width) {
        this(origin, destination, DIRECTED_DEFAULT, type, width);
    }

    public OsmEdge(NodeType origin, NodeType destination, double width) {
        this(origin, destination, DIRECTED_DEFAULT, TYPE_DEFAULT, width);
    }

    @Override
    public NodeType getOrigin() {
        return origin;
    }

    @Override
    public NodeType getDestination() {
        return destination;
    }

    @Override
    public boolean isDirected() {
        return directed;
    }

    public StreetType getType() {
        return type;
    }

    public double getWidth() {
        return width;
    }
}


